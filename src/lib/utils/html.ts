/**
 * Safe HTML escaping utility to protect against Cross-Site Scripting (XSS)
 * and HTML injection attacks in emails and server-rendered HTML documents.
 */
export function escapeHtml(str: unknown): string {
  if (str === null || str === undefined) return '';
  return String(str)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}
